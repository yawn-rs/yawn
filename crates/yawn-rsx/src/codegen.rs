use crate::ast::*;
use crate::diag::{Diagnostic, LineIndex};
use crate::parser::validate_expr;
use crate::scan;
use crate::sourcemap::{LineOrigin, SourceMap};

type Result<T> = std::result::Result<T, Diagnostic>;

const RT: &str = "__rt";

struct Writer<'a> {
    src: &'a str,
    index: LineIndex,
    text: String,
    lines: Vec<LineOrigin>,
    col: usize,
    indent: usize,
    default_origin: (u32, u32),
}

impl<'a> Writer<'a> {
    fn new(src: &'a str) -> Self {
        let mut w = Writer {
            src,
            index: LineIndex::new(src),
            text: String::new(),
            lines: Vec::new(),
            col: 0,
            indent: 0,
            default_origin: (1, 1),
        };
        w.start_line();
        w
    }

    fn start_line(&mut self) {
        self.lines.push(LineOrigin {
            src_line: self.default_origin.0,
            src_col: self.default_origin.1,
            gen_col: 0,
            exact: false,
        });
    }

    fn origin(&mut self, offset: usize) {
        let (l, c) = self.index.position(self.src, offset);
        self.default_origin = (l as u32, c as u32);
        let cur = self.lines.last_mut().unwrap();
        if !cur.exact && self.col == self.indent * 4 {
            cur.src_line = l as u32;
            cur.src_col = c as u32;
        }
    }

    fn raw(&mut self, s: &str) {
        for (i, piece) in s.split('\n').enumerate() {
            if i > 0 {
                self.newline_raw();
            }
            self.text.push_str(piece);
            self.col += piece.chars().count();
        }
    }

    fn newline_raw(&mut self) {
        self.text.push('\n');
        self.col = 0;
        self.start_line();
    }

    fn nl(&mut self) {
        self.newline_raw();
        let pad = "    ".repeat(self.indent);
        self.text.push_str(&pad);
        self.col = pad.len();
    }

    fn verbatim(&mut self, range: &Span) {
        let text = &self.src[range.clone()];
        let (l, c) = self.index.position(self.src, range.start);
        for (i, piece) in text.split('\n').enumerate() {
            if i > 0 {
                self.newline_raw();
                *self.lines.last_mut().unwrap() = LineOrigin {
                    src_line: l as u32 + i as u32,
                    src_col: 1,
                    gen_col: 1,
                    exact: true,
                };
            } else {
                *self.lines.last_mut().unwrap() = LineOrigin {
                    src_line: l as u32,
                    src_col: c as u32,
                    gen_col: self.col as u32 + 1,
                    exact: true,
                };
            }
            self.text.push_str(piece);
            self.col += piece.chars().count();
        }
    }
}

struct Gen<'a> {
    src: &'a str,
    w: Writer<'a>,
    counter: usize,
    loops: Vec<String>,
    known: &'a Registry,
}

/// The props each component of the project may leave out, by component name
pub type Registry = std::collections::BTreeMap<String, Vec<String>>;

pub fn generate(
    src: &str,
    file: &File,
    source_path: &str,
    known: &Registry,
) -> Result<(String, SourceMap)> {
    let mut g = Gen { src, w: Writer::new(src), counter: 0, loops: Vec::new(), known };
    g.w.raw(&format!(
        "// @generated by yawn-rsx from {source_path}. Do not edit; changes are overwritten."
    ));
    g.w.nl();
    g.w.raw("#[allow(unused_imports)]");
    g.w.nl();
    g.w.raw("use ::yawn::ui::prelude::*;");
    g.w.nl();
    g.w.raw(&format!("#[allow(unused_imports)]\nuse ::yawn::ui::rt as {RT};\n"));
    for item in &file.items {
        match item {
            Item::Rust(range) => g.w.verbatim(range),
            Item::Component(c) => g.component(c)?,
            Item::ServerFn(f) => g.server_fn(f),
        }
    }
    g.server_routes(file);
    g.w.raw("\n");
    let map = SourceMap { source: source_path.to_string(), lines: g.w.lines };
    Ok((g.w.text, map))
}

impl Gen<'_> {
    /// Two functions of one signature: the server's runs the body, the client's sends the
    /// arguments to it. Both return `Result`, so a component that calls one compiles for SSR too.
    fn server_fn(&mut self, f: &ServerFn) {
        let w = &mut self.w;
        w.origin(f.name_span.start);
        for server in [true, false] {
            if !w.text.ends_with('\n') {
                w.raw("\n");
            }
            // `Ok(body)` keeps a body that doesn't match the return type an error, `()` included
            let attrs = if server {
                "#[cfg(not(target_arch = \"wasm32\"))]\n#[allow(clippy::unit_arg)]"
            } else {
                "#[cfg(target_arch = \"wasm32\")]"
            };
            w.raw(&format!("{attrs}\npub async fn {}(", f.name));
            for (i, p) in f.params.iter().enumerate() {
                if i > 0 {
                    w.raw(", ");
                }
                // the client only forwards the arguments: a `mut` would be unused there
                w.verbatim(if server { &p.span } else { &p.decl });
            }
            w.raw(") -> ::core::result::Result<");
            match &f.ret {
                Some(t) => w.verbatim(t),
                None => w.raw("()"),
            }
            w.raw(", ::yawn::fns::Error> {");
            if server {
                // taken from the request before the body runs: the body's own `?` is not ours
                for e in &f.extractors {
                    w.raw(&format!(" let {} = match ::yawn::fns::extract::<", e.name));
                    w.verbatim(&e.ty);
                    w.raw(">().await { ::core::result::Result::Ok(v) => v, ::core::result::Result::Err(e) => return ::core::result::Result::Err(e) };");
                }
                w.raw(" ::core::result::Result::Ok(async move ");
                w.verbatim(&f.body);
                w.raw(".await) }");
            } else {
                let args: String = f.params.iter().map(|p| format!("{}, ", p.name)).collect();
                w.raw(&format!(
                    " ::yawn::fns::call::<::yawn::fns::codec::{}, _, _>(::yawn::fns::Method::{}, ::core::module_path!(), \"{}\", &({args})).await }}",
                    f.encoding.marker(),
                    f.method.variant(),
                    f.name
                ));
            }
        }
        w.raw("\n");
        if f.encoding == Encoding::Bits {
            self.pipelined(f);
        }
    }

    /// `name_p`: the call as a [`Pending`](yawn::fns::Pending) whose arguments may be pieces of the
    /// answers of earlier calls. In the browser it joins the batch of the tick; on the server it
    /// runs the function where it is.
    fn pipelined(&mut self, f: &ServerFn) {
        let w = &mut self.w;
        for server in [true, false] {
            w.raw(if server {
                "#[cfg(not(target_arch = \"wasm32\"))]\n"
            } else {
                "#[cfg(target_arch = \"wasm32\")]\n"
            });
            w.raw(&format!("pub fn {}_p(", f.name));
            for (i, p) in f.params.iter().enumerate() {
                if i > 0 {
                    w.raw(", ");
                }
                w.raw(&format!("{}: impl ::yawn::fns::IntoArg<", p.name));
                w.verbatim(&p.ty);
                w.raw(">");
            }
            w.raw(") -> ::yawn::fns::Pending<");
            match &f.ret {
                Some(t) => w.verbatim(t),
                None => w.raw("()"),
            }
            w.raw("> {");
            if server {
                for p in &f.params {
                    w.raw(&format!(" let {} = ::yawn::fns::IntoArg::<", p.name));
                    w.verbatim(&p.ty);
                    w.raw(&format!(">::value({});", p.name));
                }
                w.raw(" ::yawn::fns::pending(async move {");
                for p in &f.params {
                    w.raw(&format!(" let {} = {}.await?;", p.name, p.name));
                }
                let args: Vec<&str> = f.params.iter().map(|p| p.name.as_str()).collect();
                w.raw(&format!(" {}({}).await }}) }}", f.name, args.join(", ")));
            } else {
                w.raw(" let mut args = ::yawn::fns::ArgBuilder::new::<(");
                for p in &f.params {
                    w.verbatim(&p.ty);
                    w.raw(", ");
                }
                w.raw(")>();");
                for p in &f.params {
                    w.raw(" ::yawn::fns::IntoArg::<");
                    w.verbatim(&p.ty);
                    w.raw(&format!(">::part({}, &mut args);", p.name));
                }
                w.raw(" ::yawn::fns::pipe::<");
                match &f.ret {
                    Some(t) => w.verbatim(t),
                    None => w.raw("()"),
                }
                w.raw(&format!(
                    ">(::yawn::fns::Method::{}, ::core::module_path!(), \"{}\", args) }}",
                    f.method.variant(),
                    f.name
                ));
            }
            w.raw("\n");
        }
    }

    /// `__yawn_server_fns`, which adds the file's server functions to the server's routes. The
    /// client's call builds the same URL from the same `module_path!()`.
    fn server_routes(&mut self, file: &File) {
        let names: Vec<(&str, Method, Encoding)> = file
            .items
            .iter()
            .filter_map(|i| {
                if let Item::ServerFn(f) = i {
                    Some((f.name.as_str(), f.method, f.encoding))
                } else {
                    None
                }
            })
            .collect();
        if names.is_empty() {
            return;
        }
        let w = &mut self.w;
        w.raw("\n#[cfg(not(target_arch = \"wasm32\"))]\n#[doc(hidden)]\n#[allow(clippy::let_and_return)]\npub fn __yawn_server_fns(r: ::yawn::server::axum::Router) -> ::yawn::server::axum::Router {");
        for (name, method, encoding) in names {
            w.raw(&format!(
                "\n    let r = ::yawn::fns::route::<::yawn::fns::codec::{}, _, _>(r, &::yawn::fns::url(::core::module_path!(), \"{name}\"), ::yawn::fns::Method::{}, {name});",
                encoding.marker(),
                method.variant()
            ));
        }
        w.raw("\n    r\n}");
    }

    fn fresh(&mut self, prefix: &str) -> String {
        self.counter += 1;
        format!("{prefix}{}", self.counter)
    }

    fn component(&mut self, c: &Component) -> Result<()> {
        let w = &mut self.w;
        w.origin(c.name_span.start);
        // Doc comments and attributes written above `component` end up on the struct.
        if !w.text.ends_with('\n') {
            w.raw("\n");
        }
        if c.params.is_empty() {
            w.raw("#[derive(Default)]\n");
        }
        w.raw(&format!("pub struct {}", c.name));
        if let Some(g) = &c.generics {
            w.verbatim(g);
        }
        where_clause(w, c);
        w.raw(" {");
        w.indent += 1;
        for p in &c.params {
            w.nl();
            w.origin(p.span.start);
            w.raw("pub ");
            w.verbatim(&p.decl);
            w.raw(",");
        }
        w.indent -= 1;
        w.nl();
        w.origin(c.name_span.start);
        w.raw("}\n\n");
        if c.params.iter().any(|p| p.default.is_some()) {
            w.raw("#[allow(non_snake_case, clippy::all)]\n");
            impl_head(w, c, "");
            w.raw("\n");
            for p in &c.params {
                if let Some(d) = &p.default {
                    // the marker ties `Self` to the props being built: `List::__default_sep()`
                    // alone leaves the `T` of `List<T>` unknown when `sep` doesn't mention it
                    w.raw(&format!(
                        "    #[doc(hidden)]\n    pub fn __default_{}(_: ::core::marker::PhantomData<Self>) -> ",
                        p.name
                    ));
                    w.verbatim(&p.ty);
                    w.raw(" { ");
                    w.origin(d.start);
                    w.verbatim(d);
                    w.raw(" }\n");
                }
            }
            w.raw("}\n\n");
        }
        w.raw("#[allow(unused_parens, unused_braces, unused_mut, clippy::all)]\n");
        // the registry is filled at startup, before any `T` is known. The code of `List<u8>` is
        // in whatever renders it, and a side module with that code swaps it
        let dynamic = dynamic() && c.generics.is_none() && c.where_clause.is_none();
        if dynamic {
            w.raw(&format!(
                "impl {} {{\n    #[doc(hidden)]\n    pub fn __yawn_body(self) -> ::yawn::ui::View {{\n        {BODY_BEGIN}",
                c.name
            ));
        } else {
            impl_head(w, c, "::yawn::ui::Component for ");
            w.raw("\n    fn render(self) -> ::yawn::ui::View {");
        }
        w.indent = 2;
        if !c.params.is_empty() {
            w.nl();
            let names: Vec<_> = c.params.iter().map(|p| p.name.as_str()).collect();
            w.raw(&format!("let Self {{ {} }} = self;", names.join(", ")));
        }
        w.nl();
        w.verbatim(&c.setup);
        w.nl();
        let root = self.fresh("__f");
        self.w.raw(&format!("let mut {root} = {RT}::Frag::new();"));
        self.children(&c.view, &format!("&mut {root}"))?;
        self.w.nl();
        self.w.raw(&format!("{root}.finish()"));
        if dynamic {
            self.w.nl();
            self.w.raw(BODY_END);
        }
        self.w.indent = 1;
        self.w.nl();
        self.w.raw("}");
        self.w.indent = 0;
        self.w.nl();
        self.w.raw("}\n");
        if dynamic {
            let name = &c.name;
            self.w.raw(&format!(
                "\n#[allow(unused_parens, unused_braces, unused_mut, clippy::all)]\nimpl {name} {{\n    #[doc(hidden)]\n    pub fn __yawn_register() {{\n        ::yawn::dynamic::register::<Self>(::core::any::type_name::<Self>(), Self::__yawn_body);\n    }}\n}}\n\n#[cfg(target_os = \"linux\")]\n#[allow(non_upper_case_globals)]\n#[used]\n#[unsafe(link_section = \".init_array\")]\nstatic __YAWN_REGISTER_{name}: extern \"C\" fn() = {{\n    extern \"C\" fn register() {{\n        {name}::__yawn_register();\n    }}\n    register\n}};\n\n#[cfg(target_os = \"macos\")]\n#[allow(non_upper_case_globals)]\n#[used]\n#[unsafe(link_section = \"__DATA,__mod_init_func\")]\nstatic __YAWN_REGISTER_MAC_{name}: extern \"C\" fn() = {{\n    extern \"C\" fn register() {{\n        {name}::__yawn_register();\n    }}\n    register\n}};\n\n#[allow(unused_parens, unused_braces, unused_mut, clippy::all)]\nimpl ::yawn::ui::Component for {name} {{\n    fn render(self) -> ::yawn::ui::View {{\n        match ::yawn::dynamic::entry::<Self>(::core::any::type_name::<Self>()) {{\n            Some(f) => f(self),\n            None => Self::__yawn_body(self),\n        }}\n    }}\n}}\n"
            ));
        }
        Ok(())
    }

    fn spans_of(nodes: &[Node], out: &mut Vec<Span>) {
        for n in nodes {
            match n {
                Node::Expr(s) => out.push(s.clone()),
                Node::Text(t) => Self::text_spans(t, out),
                Node::Slot(..) => {}
                Node::Element(e) => {
                    for a in &e.attrs {
                        match &a.value {
                            AttrValue::Flag => {}
                            AttrValue::Text(t) => Self::text_spans(t, out),
                            AttrValue::Expr(s) => out.push(s.clone()),
                        }
                    }
                    Self::spans_of(&e.children, out);
                }
                Node::If(i) => {
                    out.push(i.cond.clone());
                    Self::spans_of(&i.then, out);
                    if let Some(o) = &i.otherwise {
                        Self::spans_of(o, out);
                    }
                }
                Node::For(f) => {
                    out.push(f.iter.clone());
                    out.push(f.key.clone());
                    Self::spans_of(&f.body, out);
                }
            }
        }
    }

    fn text_spans(t: &Text, out: &mut Vec<Span>) {
        for p in &t.parts {
            if let Part::Interp { expr, .. } = p {
                out.push(expr.clone());
            }
        }
    }

    fn used_loops(&self, spans: &[Span]) -> Vec<String> {
        self.loops
            .iter()
            .filter(|v| spans.iter().any(|s| scan::mentions(&self.src[s.clone()], v)))
            .cloned()
            .collect()
    }

    fn cloned(&mut self, spans: &[Span], body: impl FnOnce(&mut Self) -> Result<()>) -> Result<()> {
        let used = self.used_loops(spans);
        if used.is_empty() {
            return body(self);
        }
        let lets: String =
            used.iter().map(|v| format!("let {v} = ::core::clone::Clone::clone(&{v}); ")).collect();
        self.w.raw(&format!("{{ {lets}"));
        body(self)?;
        self.w.raw(" }");
        Ok(())
    }

    fn expr(&mut self, span: &Span) -> Result<()> {
        let plain = validate_expr(self.src, span.clone())?;
        self.w.raw(if plain { "(" } else { "{" });
        self.w.verbatim(span);
        self.w.raw(if plain { ")" } else { "}" });
        Ok(())
    }

    fn format(&mut self, t: &Text) -> Result<()> {
        let mut fmt = String::new();
        for p in &t.parts {
            match p {
                Part::Lit(s) => fmt.push_str(&self.src[s.clone()]),
                Part::Interp { spec: None, .. } => fmt.push_str("{}"),
                Part::Interp { spec: Some(s), .. } => {
                    fmt.push_str(&format!("{{:{}}}", &self.src[s.clone()]))
                }
            }
        }
        self.w.raw(&format!("::std::format!(\"{fmt}\""));
        for p in &t.parts {
            if let Part::Interp { expr, .. } = p {
                self.w.raw(", ");
                self.expr(expr)?;
            }
        }
        self.w.raw(")");
        Ok(())
    }

    fn static_str(&mut self, t: &Text) {
        let lit = self.src[t.span.clone()].replace("{{", "{").replace("}}", "}");
        self.w.raw(&lit);
    }

    fn children(&mut self, nodes: &[Node], sink: &str) -> Result<()> {
        for n in nodes {
            self.node(n, sink)?;
        }
        Ok(())
    }

    fn node(&mut self, node: &Node, sink: &str) -> Result<()> {
        match node {
            Node::Text(t) => {
                self.w.nl();
                self.w.origin(t.span.start);
                self.w.raw(&format!("{RT}::add({sink}, "));
                if t.is_static() {
                    self.w.raw(&format!("{RT}::text_lit("));
                    self.static_str(t);
                    self.w.raw(")");
                } else {
                    let mut spans = Vec::new();
                    Self::text_spans(t, &mut spans);
                    self.w.raw(&format!("{RT}::text_fmt("));
                    self.cloned(&spans, |g| {
                        g.w.raw("move || ");
                        g.format(t)
                    })?;
                    self.w.raw(")");
                }
                self.w.raw(");");
            }
            Node::Expr(span) => {
                self.w.nl();
                self.w.origin(span.start);
                self.w.raw(&format!("{RT}::add({sink}, {RT}::dyn_child("));
                self.cloned(std::slice::from_ref(span), |g| {
                    g.w.raw("move || ");
                    g.expr(span)
                })?;
                self.w.raw("));");
            }
            Node::Slot(span, name) => {
                self.w.nl();
                self.w.origin(span.start);
                self.w.raw(&format!(
                    "{RT}::add({sink}, {}.view());",
                    name.as_deref().unwrap_or("children")
                ));
            }
            Node::If(i) => {
                self.w.nl();
                self.w.origin(i.span.start);
                self.if_node(i, sink)?;
            }
            Node::For(f) => {
                self.w.nl();
                self.w.origin(f.span.start);
                self.for_node(f, sink)?;
            }
            Node::Element(e) if e.is_component => self.component_use(e, sink)?,
            Node::Element(e) => self.element(e, sink)?,
        }
        Ok(())
    }

    fn builder(&mut self, nodes: &[Node]) -> Result<()> {
        let f = self.fresh("__f");
        self.w.raw("move || {");
        self.w.indent += 1;
        self.w.nl();
        self.w.raw(&format!("let mut {f} = {RT}::Frag::new();"));
        self.children(nodes, &format!("&mut {f}"))?;
        self.w.nl();
        self.w.raw(&format!("{f}.finish()"));
        self.w.indent -= 1;
        self.w.nl();
        self.w.raw("}");
        Ok(())
    }

    fn if_node(&mut self, i: &If, sink: &str) -> Result<()> {
        if let Some((pat, value)) = &i.binding {
            return self.if_let_node(i, pat, value, sink);
        }
        self.w.raw(&format!("{RT}::add({sink}, {RT}::show("));
        self.w.indent += 1;
        self.w.nl();
        self.cloned(std::slice::from_ref(&i.cond), |g| {
            g.w.raw("move || ");
            g.expr(&i.cond)
        })?;
        self.w.raw(",");
        self.w.nl();
        let mut spans = Vec::new();
        Self::spans_of(&i.then, &mut spans);
        self.cloned(&spans, |g| g.builder(&i.then))?;
        self.w.raw(",");
        self.w.nl();
        match &i.otherwise {
            None => self.w.raw(&format!("|| {RT}::View::empty()")),
            Some(nodes) => {
                let mut spans = Vec::new();
                Self::spans_of(nodes, &mut spans);
                self.cloned(&spans, |g| g.builder(nodes))?;
            }
        }
        self.w.indent -= 1;
        self.w.nl();
        self.w.raw("));");
        Ok(())
    }

    fn if_let_node(&mut self, i: &If, pat: &Span, value: &Span, sink: &str) -> Result<()> {
        let key = self.fresh("__v");
        self.w.raw(&format!("{RT}::add({sink}, {RT}::switch("));
        self.w.indent += 1;
        self.w.nl();
        self.cloned(std::slice::from_ref(value), |g| {
            g.w.raw("move || ");
            g.expr(value)
        })?;
        self.w.raw(",");
        self.w.nl();
        let mut spans = Vec::new();
        Self::spans_of(&i.then, &mut spans);
        if let Some(o) = &i.otherwise {
            Self::spans_of(o, &mut spans);
        }
        self.cloned(&spans, |g| {
            g.w.raw(&format!("move |{key}| "));
            g.w.raw("if let ");
            g.w.verbatim(pat);
            g.w.raw(&format!(" = {key} "));
            let outer = g.loops.len();
            g.loops.extend(pattern_vars(&g.src[pat.clone()]));
            g.block(&i.then)?;
            g.loops.truncate(outer);
            g.w.raw(" else ");
            match &i.otherwise {
                None => g.w.raw(&format!("{{ {RT}::View::empty() }}")),
                Some(nodes) => g.block(nodes)?,
            }
            Ok(())
        })?;
        self.w.indent -= 1;
        self.w.nl();
        self.w.raw("));");
        Ok(())
    }

    fn block(&mut self, nodes: &[Node]) -> Result<()> {
        let f = self.fresh("__f");
        self.w.raw("{");
        self.w.indent += 1;
        self.w.nl();
        self.w.raw(&format!("let mut {f} = {RT}::Frag::new();"));
        self.children(nodes, &format!("&mut {f}"))?;
        self.w.nl();
        self.w.raw(&format!("{f}.finish()"));
        self.w.indent -= 1;
        self.w.nl();
        self.w.raw("}");
        Ok(())
    }

    fn for_node(&mut self, f: &For, sink: &str) -> Result<()> {
        let (pat, iter, key) = (&f.pat, &f.iter, &f.key);
        self.w.raw(&format!("{RT}::add({sink}, {RT}::each("));
        self.w.indent += 1;
        self.w.nl();
        let used = self.used_loops(std::slice::from_ref(iter));
        self.cloned(std::slice::from_ref(iter), |g| {
            // The closure runs on every change of the list, but `into_iter` consumes: hand it a copy.
            let again: String = used
                .iter()
                .map(|v| format!("let {v} = ::core::clone::Clone::clone(&{v}); "))
                .collect();
            g.w.raw(&format!("move || {{ {again}::std::iter::IntoIterator::into_iter("));
            g.expr(iter)?;
            g.w.raw(").collect::<::std::vec::Vec<_>>() }");
            Ok(())
        })?;
        self.w.raw(",");
        self.w.nl();
        let vars = pattern_vars(&self.src[pat.clone()]);
        let key_vars = vars.clone();
        self.cloned(std::slice::from_ref(key), |g| {
            let vars = key_vars;
            g.w.raw("move |");
            g.w.verbatim(pat);
            g.w.raw("| ");
            // The key often ignores part of the pattern; mark every binding as used.
            let uses: String = vars.iter().map(|v| format!("&{v}, ")).collect();
            g.w.raw(&format!("{{ let _ = ({uses}); "));
            g.expr(key)?;
            g.w.raw(" }");
            Ok(())
        })?;
        self.w.raw(",");
        self.w.nl();
        let mut spans = Vec::new();
        Self::spans_of(&f.body, &mut spans);
        let outer = self.loops.len();
        self.loops.extend(vars);
        // Outer loop variables used in the body are cloned for the row closure; the row's own
        // variables are parameters of that closure.
        let used_outer: Vec<String> = self.loops[..outer]
            .iter()
            .filter(|v| spans.iter().any(|s| scan::mentions(&self.src[s.clone()], v)))
            .cloned()
            .collect();
        if !used_outer.is_empty() {
            let lets: String = used_outer
                .iter()
                .map(|v| format!("let {v} = ::core::clone::Clone::clone(&{v}); "))
                .collect();
            self.w.raw(&format!("{{ {lets}"));
        }
        let fr = self.fresh("__f");
        self.w.raw("move |");
        self.w.verbatim(pat);
        self.w.raw("| {");
        self.w.indent += 1;
        self.w.nl();
        self.w.raw(&format!("let mut {fr} = {RT}::Frag::new();"));
        self.children(&f.body, &format!("&mut {fr}"))?;
        self.w.nl();
        self.w.raw(&format!("{fr}.finish()"));
        self.w.indent -= 1;
        self.w.nl();
        self.w.raw("}");
        if !used_outer.is_empty() {
            self.w.raw(" }");
        }
        self.loops.truncate(outer);
        self.w.indent -= 1;
        self.w.nl();
        self.w.raw("));");
        Ok(())
    }

    fn element(&mut self, e: &Element, sink: &str) -> Result<()> {
        if let Some(html) = self.static_html(e) {
            self.w.nl();
            self.w.origin(e.name_span.start);
            self.w.raw(&format!("{RT}::add({sink}, {RT}::template({html:?}));"));
            return Ok(());
        }
        if let Some(sk) = self.skeleton(e) {
            return self.skeleton_code(e, sk, sink);
        }
        let id = self.fresh("__e");
        self.w.nl();
        self.w.origin(e.name_span.start);
        self.w.raw(&format!("let {id} = {RT}::element(\"{}\");", e.name));
        for a in &e.attrs {
            self.w.nl();
            self.w.origin(a.name_span.start);
            self.attr(&id, a)?;
        }
        self.children(&e.children, &id)?;
        self.w.nl();
        self.w.origin(e.name_span.start);
        self.w.raw(&format!("{RT}::add({sink}, {id});"));
        Ok(())
    }

    fn skeleton(&self, e: &Element) -> Option<Skeleton> {
        let mut sk = Skeleton { html: String::new(), paths: vec![Vec::new()] };
        self.skeleton_element(e, &mut Vec::new(), &mut Vec::new(), &mut sk)?;
        // a bare element with nothing literal in it is cheaper to create directly
        let bare =
            sk.html == format!("<{}></{}>", e.name, e.name) || sk.html == format!("<{}>", e.name);
        (sk.paths.len() > 1 || !bare).then_some(sk)
    }

    fn markup_attr(&self, a: &Attr) -> Option<String> {
        let name = a.name.as_str();
        if name.is_empty()
            || !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
            || name == "slot"
        {
            return None;
        }
        match &a.value {
            AttrValue::Flag => Some(String::new()),
            AttrValue::Text(t) => self.static_text(t).filter(|v| !v.starts_with("/assets/")),
            AttrValue::Expr(_) => None,
        }
    }

    fn is_hole(&self, e: &Element) -> bool {
        e.attrs.iter().any(|a| self.markup_attr(a).is_none())
            || e.children.iter().any(|c| match c {
                Node::Element(c) => c.is_component,
                Node::Text(t) => !t.is_static(),
                _ => true,
            })
    }

    fn skeleton_element<'e>(
        &self,
        e: &'e Element,
        ancestors: &mut Vec<&'e str>,
        path: &mut Vec<u8>,
        sk: &mut Skeleton,
    ) -> Option<()> {
        let name = e.name.as_str();
        let valid_name = name.starts_with(|c: char| c.is_ascii_lowercase())
            && name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
        if e.is_component || !valid_name || !html_nesting_is_stable(name, ancestors) {
            return None;
        }
        let void = yawn_void(name);
        if void && !e.children.is_empty() {
            return None;
        }
        if !path.is_empty() && self.is_hole(e) {
            sk.paths.push(path.clone());
        }
        let out = &mut sk.html;
        out.push('<');
        out.push_str(name);
        let mut seen: Vec<&str> = Vec::new();
        for a in &e.attrs {
            if a.name == "slot" {
                return None;
            }
            let Some(value) = self.markup_attr(a) else {
                continue;
            };
            if seen.contains(&a.name.as_str()) {
                return None;
            }
            seen.push(&a.name);
            out.push(' ');
            out.push_str(&a.name);
            out.push_str("=\"");
            for c in value.chars() {
                match c {
                    '&' => out.push_str("&amp;"),
                    '"' => out.push_str("&quot;"),
                    '<' => out.push_str("&lt;"),
                    '>' => out.push_str("&gt;"),
                    c => out.push(c),
                }
            }
            out.push('"');
        }
        out.push('>');
        if void {
            return Some(());
        }
        ancestors.push(name);
        let mut index = 0usize;
        let (mut dynamic, mut after_text) = (false, false);
        for child in &e.children {
            match child {
                Node::Element(c) if !c.is_component => {
                    if dynamic || index > 250 {
                        return None;
                    }
                    path.push(index as u8);
                    self.skeleton_element(c, ancestors, path, sk)?;
                    path.pop();
                    index += 1;
                    after_text = false;
                }
                Node::Text(t) if t.is_static() => {
                    // two literals in a row would be read back as one text node
                    let v = self.static_text(t).filter(|v| !v.is_empty())?;
                    if dynamic || after_text || index > 250 {
                        return None;
                    }
                    for c in v.chars() {
                        match c {
                            '&' => sk.html.push_str("&amp;"),
                            '<' => sk.html.push_str("&lt;"),
                            '>' => sk.html.push_str("&gt;"),
                            c => sk.html.push(c),
                        }
                    }
                    index += 1;
                    after_text = true;
                }
                _ => dynamic = true,
            }
        }
        ancestors.pop();
        sk.html.push_str("</");
        sk.html.push_str(name);
        sk.html.push('>');
        Some(())
    }

    fn skeleton_code(&mut self, e: &Element, sk: Skeleton, sink: &str) -> Result<()> {
        let vars: Vec<String> = sk.paths.iter().map(|_| self.fresh("__e")).collect();
        let paths: Vec<String> = sk
            .paths
            .iter()
            .map(|p| {
                format!("&[{}]", p.iter().map(|i| format!("{i}u8")).collect::<Vec<_>>().join(", "))
            })
            .collect();
        self.w.nl();
        self.w.origin(e.name_span.start);
        self.w.raw(&format!(
            "let [{}] = {RT}::template_holes({:?}, &[{}]);",
            vars.join(", "),
            sk.html,
            paths.join(", ")
        ));
        let mut next = 1;
        self.hole_code(e, &vars, &mut next, true)?;
        self.w.nl();
        self.w.origin(e.name_span.start);
        self.w.raw(&format!("{RT}::add({sink}, {});", vars[0]));
        Ok(())
    }

    fn hole_code(
        &mut self,
        e: &Element,
        vars: &[String],
        next: &mut usize,
        root: bool,
    ) -> Result<()> {
        let var = if root {
            Some(0)
        } else if self.is_hole(e) {
            *next += 1;
            Some(*next - 1)
        } else {
            None
        };
        if let Some(v) = var {
            for a in &e.attrs {
                if self.markup_attr(a).is_none() {
                    self.w.nl();
                    self.w.origin(a.name_span.start);
                    self.attr(&vars[v], a)?;
                }
            }
        }
        for child in &e.children {
            match child {
                Node::Element(c) if !c.is_component => self.hole_code(c, vars, next, false)?,
                Node::Text(t) if t.is_static() => {}
                other => {
                    let v = var.expect("a dynamic child makes its element a hole");
                    self.node(other, &vars[v])?;
                }
            }
        }
        Ok(())
    }

    fn static_html(&self, e: &Element) -> Option<String> {
        let mut out = String::new();
        self.static_element(e, &mut Vec::new(), &mut out).then_some(out)
    }

    fn static_element<'e>(
        &self,
        e: &'e Element,
        ancestors: &mut Vec<&'e str>,
        out: &mut String,
    ) -> bool {
        let name = e.name.as_str();
        let valid_name = name.starts_with(|c: char| c.is_ascii_lowercase())
            && name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
        if e.is_component || !valid_name || !html_nesting_is_stable(name, ancestors) {
            return false;
        }
        let void = yawn_void(name);
        if void && !e.children.is_empty() {
            return false;
        }
        out.push('<');
        out.push_str(name);
        let mut seen: Vec<&str> = Vec::new();
        for a in &e.attrs {
            let an = a.name.as_str();
            let valid = !an.is_empty()
                && an.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
            if !valid || an == "slot" || seen.contains(&an) {
                return false;
            }
            seen.push(an);
            let value = match &a.value {
                AttrValue::Flag => String::new(),
                AttrValue::Text(t) => match self.static_text(t) {
                    Some(v) if !v.starts_with("/assets/") => v,
                    _ => return false,
                },
                AttrValue::Expr(_) => return false,
            };
            out.push(' ');
            out.push_str(an);
            out.push_str("=\"");
            for c in value.chars() {
                match c {
                    '&' => out.push_str("&amp;"),
                    '"' => out.push_str("&quot;"),
                    '<' => out.push_str("&lt;"),
                    '>' => out.push_str("&gt;"),
                    c => out.push(c),
                }
            }
            out.push('"');
        }
        out.push('>');
        if void {
            return true;
        }
        ancestors.push(name);
        for child in &e.children {
            let ok = match child {
                Node::Element(c) => self.static_element(c, ancestors, out),
                Node::Text(t) => match self.static_text(t) {
                    Some(v) if !v.is_empty() => {
                        for c in v.chars() {
                            match c {
                                '&' => out.push_str("&amp;"),
                                '<' => out.push_str("&lt;"),
                                '>' => out.push_str("&gt;"),
                                c => out.push(c),
                            }
                        }
                        true
                    }
                    _ => false,
                },
                _ => false,
            };
            if !ok {
                return false;
            }
        }
        ancestors.pop();
        out.push_str("</");
        out.push_str(name);
        out.push('>');
        true
    }

    fn static_text(&self, t: &Text) -> Option<String> {
        let mut value = String::new();
        for part in &t.parts {
            let Part::Lit(span) = part else { return None };
            let lit = &self.src[span.clone()];
            if lit.contains(['\\', '{', '}']) {
                return None;
            }
            value.push_str(lit);
        }
        Some(value)
    }

    fn attr(&mut self, id: &str, a: &Attr) -> Result<()> {
        let name = a.name.as_str();
        let mut spans = Vec::new();
        match &a.value {
            AttrValue::Flag => {}
            AttrValue::Text(t) => Self::text_spans(t, &mut spans),
            AttrValue::Expr(s) => spans.push(s.clone()),
        }
        if name == "ref" {
            let AttrValue::Expr(expr) = &a.value else {
                return Err(Diagnostic::new(
                    "`ref` needs a handle: `ref={node}`".to_string(),
                    a.name_span.clone(),
                ));
            };
            self.w.raw(&format!("{RT}::bind_ref({id}, "));
            self.expr(expr)?;
            self.w.raw(");");
            return Ok(());
        }
        if let Some(event) = name.strip_prefix("on:") {
            let AttrValue::Expr(expr) = &a.value else {
                return Err(Diagnostic::new(
                    format!("`{name}` needs a handler: `{name}={{move || ...}}`"),
                    a.name_span.clone(),
                ));
            };
            return self.cloned(&spans, |g| {
                g.w.raw(&format!("{RT}::listen({id}, \"{event}\", "));
                g.expr(expr)?;
                g.w.raw(");");
                Ok(())
            });
        }
        for (prefix, func) in [("class:", "bind_class"), ("prop:", "bind_prop")] {
            if let Some(target) = name.strip_prefix(prefix) {
                let AttrValue::Expr(expr) = &a.value else {
                    return Err(Diagnostic::new(
                        format!("`{name}` needs an expression: `{name}={{...}}`"),
                        a.name_span.clone(),
                    ));
                };
                return self.cloned(&spans, |g| {
                    g.w.raw(&format!("{RT}::{func}({id}, \"{target}\", move || "));
                    g.expr(expr)?;
                    g.w.raw(");");
                    Ok(())
                });
            }
        }
        if name.contains(':') {
            return Err(Diagnostic::new(
                format!("unknown directive in `{name}`"),
                a.name_span.clone(),
            )
            .help(
                "supported: `on:event={handler}`, `class:name={condition}`, `prop:name={value}`, `ref={node}`",
            ));
        }
        match &a.value {
            AttrValue::Flag => self.w.raw(&format!("{RT}::attr_lit({id}, \"{name}\", \"\");")),
            AttrValue::Text(t) if t.is_static() => {
                self.w.raw(&format!("{RT}::attr_lit({id}, \"{name}\", "));
                self.static_str(t);
                self.w.raw(");");
            }
            AttrValue::Text(t) => {
                return self.cloned(&spans, |g| {
                    g.w.raw(&format!("{RT}::bind_attr({id}, \"{name}\", move || "));
                    g.format(t)?;
                    g.w.raw(");");
                    Ok(())
                });
            }
            AttrValue::Expr(expr) => {
                return self.cloned(&spans, |g| {
                    g.w.raw(&format!("{RT}::bind_attr({id}, \"{name}\", move || "));
                    g.expr(expr)?;
                    g.w.raw(");");
                    Ok(())
                });
            }
        }
        Ok(())
    }

    fn slot_of(&self, c: &Element) -> Option<String> {
        let a = c.attrs.iter().find(|a| a.name == "slot")?;
        match &a.value {
            AttrValue::Text(t) if t.is_static() => {
                Some(self.src[t.span.start + 1..t.span.end - 1].to_string())
            }
            _ => None,
        }
    }

    fn component_use(&mut self, e: &Element, sink: &str) -> Result<()> {
        // what the caller wrote between the tags: children that name a slot (`slot="x"`, or the
        // contents of `<template slot="x">`) fill that prop, everything else is `children`
        let mut named: Vec<(String, Vec<Node>)> = Vec::new();
        let mut rest: Vec<Node> = Vec::new();
        for n in &e.children {
            let Node::Element(c) = n else {
                rest.push(n.clone());
                continue;
            };
            let Some(slot) = self.slot_of(c) else {
                rest.push(n.clone());
                continue;
            };
            let nodes = if c.name == "template" && !c.is_component {
                c.children.clone()
            } else {
                let mut inner = c.clone();
                inner.attrs.retain(|a| a.name != "slot");
                vec![Node::Element(inner)]
            };
            match named.iter_mut().find(|(k, _)| *k == slot) {
                Some((_, all)) => all.extend(nodes),
                None => named.push((slot, nodes)),
            }
        }
        // props the caller left out take the default their component declared; a prop a slot fills is
        // not left out
        let known = self.known;
        let last = e.name.rsplit("::").next().unwrap_or(&e.name);
        let filled = |n: &str| {
            e.attrs.iter().any(|a| a.name == n)
                || named.iter().any(|(k, _)| k == n)
                || (n == "children" && !rest.is_empty())
        };
        let left_out: Vec<&String> =
            known.get(last).into_iter().flatten().filter(|n| !filled(n)).collect();
        let marker = (!left_out.is_empty()).then(|| self.fresh("__d"));
        self.w.nl();
        self.w.origin(e.name_span.start);
        self.w.raw(&format!("{RT}::add({sink}, ::yawn::ui::Component::render("));
        if let Some(d) = &marker {
            self.w.raw(&format!(
                "{{ let {d} = ::core::marker::PhantomData; {RT}::with_defaults({d}, "
            ));
        }
        self.w.raw(&format!("{} {{", e.name));
        self.w.indent += 1;
        for a in &e.attrs {
            if a.name == "ref" {
                return Err(Diagnostic::new("`ref` is not a prop name".to_string(), a.name_span.clone())
                    .help("`ref={node}` only works on HTML elements; pass the handle as a prop with another name"));
            }
            if a.name.contains(':') || a.name.contains('-') {
                return Err(Diagnostic::new(format!("`{}` is not a prop name", a.name), a.name_span.clone())
                    .help("component props are plain Rust field names; directives like `on:` only work on HTML elements"));
            }
            self.w.nl();
            self.w.origin(a.name_span.start);
            self.w.raw(&format!("{}: ", a.name));
            match &a.value {
                AttrValue::Flag => self.w.raw("true"),
                AttrValue::Text(t) if t.is_static() => {
                    self.w.raw("::core::convert::Into::into(");
                    self.static_str(t);
                    self.w.raw(")");
                }
                AttrValue::Text(t) => {
                    // a built string, which a `Class` (or any `From<String>`) prop takes as well
                    self.w.raw("::core::convert::Into::into(");
                    self.format(t)?;
                    self.w.raw(")");
                }
                AttrValue::Expr(s) => self.expr(s)?,
            }
            self.w.raw(",");
        }
        if let Some(d) = &marker {
            for name in left_out {
                self.w.nl();
                self.w.raw(&format!("{name}: {}::__default_{name}({d}),", e.name));
            }
        }
        for (field, nodes) in named
            .iter()
            .map(|(k, v)| (k.as_str(), v))
            .chain((!rest.is_empty()).then_some(("children", &rest)))
        {
            self.w.nl();
            self.w.origin(e.name_span.start);
            let mut spans = Vec::new();
            Self::spans_of(nodes, &mut spans);
            self.w.raw(&format!("{field}: "));
            self.cloned(&spans, |g| {
                g.w.raw("::yawn::ui::Children::new(");
                g.builder(nodes)?;
                g.w.raw(")");
                Ok(())
            })?;
            self.w.raw(",");
        }
        self.w.indent -= 1;
        self.w.nl();
        self.w.origin(e.name_span.start);
        self.w.raw(if marker.is_some() { "}) }));" } else { "}));" });
        Ok(())
    }
}

struct Skeleton {
    html: String,
    paths: Vec<Vec<u8>>,
}

/// Marks the part of a generated component a running page can swap out (see `yawn::dynamic`)
pub const BODY_BEGIN: &str = "// yawn:body-begin";
pub const BODY_END: &str = "// yawn:body-end";

static DYNAMIC: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);

/// `impl<T: Bound> {what}Name<T> where .. {` with the bounds as written, so an error in one points
/// at the `.rsx` file
fn impl_head(w: &mut Writer, c: &Component, what: &str) {
    w.raw("impl");
    if let Some(g) = &c.generics {
        w.verbatim(g);
    }
    w.raw(&format!(" {what}{}{}", c.name, c.generic_args));
    where_clause(w, c);
    w.raw(" {");
}

fn where_clause(w: &mut Writer, c: &Component) {
    if let Some(wc) = &c.where_clause {
        w.raw(" ");
        w.verbatim(wc);
        // it may end in a `//` comment
        w.raw("\n");
    }
}

/// Makes generated components render through `yawn::dynamic`, so a dev build can replace a
/// component's body without rebuilding the app
pub fn set_dynamic(on: bool) {
    DYNAMIC.store(on, std::sync::atomic::Ordering::Relaxed);
}

pub fn dynamic() -> bool {
    DYNAMIC.load(std::sync::atomic::Ordering::Relaxed)
}

fn yawn_void(name: &str) -> bool {
    matches!(
        name,
        "area"
            | "base"
            | "br"
            | "col"
            | "embed"
            | "hr"
            | "img"
            | "input"
            | "link"
            | "meta"
            | "param"
            | "source"
            | "track"
            | "wbr"
    )
}

fn html_nesting_is_stable(name: &str, ancestors: &[&str]) -> bool {
    const NEVER: [&str; 24] = [
        "html",
        "head",
        "body",
        "table",
        "caption",
        "colgroup",
        "col",
        "tbody",
        "thead",
        "tfoot",
        "tr",
        "td",
        "th",
        "select",
        "option",
        "optgroup",
        "textarea",
        "pre",
        "listing",
        "plaintext",
        "xmp",
        "script",
        "style",
        "title",
    ];
    const NEVER_TOO: [&str; 8] =
        ["iframe", "noscript", "template", "noembed", "noframes", "math", "frameset", "frame"];
    const BLOCK: [&str; 33] = [
        "address",
        "article",
        "aside",
        "blockquote",
        "center",
        "details",
        "dialog",
        "dir",
        "div",
        "dl",
        "fieldset",
        "figcaption",
        "figure",
        "footer",
        "header",
        "hgroup",
        "main",
        "menu",
        "nav",
        "ol",
        "p",
        "section",
        "summary",
        "ul",
        "h1",
        "h2",
        "h3",
        "h4",
        "h5",
        "h6",
        "hr",
        "form",
        "li",
    ];
    // tags that end SVG (foreign content) and continue in HTML
    const BREAKOUT: [&str; 22] = [
        "b", "big", "br", "code", "dd", "dt", "em", "embed", "i", "img", "listing", "nobr", "ruby",
        "s", "small", "span", "strike", "strong", "sub", "sup", "tt", "u",
    ];
    if NEVER.contains(&name) || NEVER_TOO.contains(&name) {
        return false;
    }
    let heading = |n: &str| matches!(n, "h1" | "h2" | "h3" | "h4" | "h5" | "h6");
    if ancestors.contains(&"p")
        && (BLOCK.contains(&name) || matches!(name, "dd" | "dt" | "table" | "pre"))
    {
        return false;
    }
    if ancestors.contains(&"svg")
        && (BLOCK.contains(&name) || BREAKOUT.contains(&name) || name == "var")
    {
        return false;
    }
    match name {
        "a" | "button" | "form" | "nobr" if ancestors.contains(&name) => return false,
        "li" if ancestors.iter().rev().find(|a| matches!(**a, "li" | "ul" | "ol"))
            == Some(&"li") =>
        {
            return false;
        }
        "dd" | "dt"
            if ancestors
                .iter()
                .rev()
                .find(|a| matches!(**a, "dd" | "dt" | "dl"))
                .is_some_and(|a| *a != "dl") =>
        {
            return false;
        }
        _ if heading(name) && ancestors.iter().any(|a| heading(a)) => return false,
        _ => {}
    }
    true
}

fn pattern_vars(pat: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut i = 0;
    while i < pat.len() {
        let Ok((kind, end)) = scan::token(pat, i) else {
            break;
        };
        if kind == scan::Kind::Ident {
            let word = &pat[i..end];
            let next = pat[end..].trim_start();
            let is_field = next.starts_with(':') && !next.starts_with("::");
            if !is_field
                && !matches!(word, "mut" | "ref" | "_" | "box")
                && word.starts_with(|c: char| c.is_lowercase() || c == '_')
                && !next.starts_with('(')
                && !next.starts_with("::")
            {
                out.push(word.to_string());
            }
        }
        i = end;
    }
    out
}
