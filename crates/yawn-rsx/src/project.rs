use crate::SourceMap;
use crate::diag::Diagnostic;
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

/// Where generated code goes, relative to the project root
pub const OUT_DIR: &str = ".yawn/rsx";
/// The entry point of a project
pub const ENTRY: &str = "main.rsx";
/// Generated crate roots (client: WASM library, server: binary) for a project with an entry point
pub const CLIENT_ROOT: &str = ".yawn/client.rs";
pub const SERVER_ROOT: &str = ".yawn/server.rs";

/// The client crate root generated from the Rust of `main.rsx`: that code, then the other modules,
/// then the mount of `App`
pub fn client_root(root: &Path, main_rust: &str) -> String {
    let mut body = String::new();
    for line in main_rust.lines() {
        body.push_str(&path_mod(root, line));
        body.push('\n');
    }
    let api = match crate::api::scan(root) {
        Ok(e) if !e.is_empty() => {
            crate::api::mod_decl(&root.join(OUT_DIR).join(crate::api::MODULE_DIR))
        }
        _ => String::new(),
    };
    format!(
        "{body}{}{api}\ninclude!(\"rsx/modules.rs\");\n\n#[cfg(target_arch = \"wasm32\")]\nyawn::client!(App);\n",
        server_mod(root)
    )
}

fn server_file(root: &Path) -> Option<PathBuf> {
    let src = root.join("src");
    [src.join("server.rs"), src.join("server").join("mod.rs")].into_iter().find(|f| f.is_file())
}

fn server_mod(root: &Path) -> String {
    match server_file(root) {
        Some(f) => format!(
            "\n#[cfg(not(target_arch = \"wasm32\"))]\n#[path = {:?}]\npub mod server;\n",
            slashed(&f)
        ),
        None => String::new(),
    }
}

/// A path as written in a generated `#[path]`: forward slashes on every system, which Rust accepts on
/// Windows too, so the generated code reads the same everywhere
fn slashed(p: &Path) -> String {
    let s = p.to_string_lossy();
    if cfg!(windows) { s.replace('\\', "/") } else { s.into_owned() }
}

fn path_mod(root: &Path, line: &str) -> String {
    path_mod_in(&root.join("src"), line)
}

fn path_mod_in(dir: &Path, line: &str) -> String {
    let t = line.trim_start();
    let rest = t.strip_prefix("pub(crate) ").or_else(|| t.strip_prefix("pub ")).unwrap_or(t);
    let Some(name) = rest.strip_prefix("mod ").and_then(|r| r.trim_end().strip_suffix(';')) else {
        return line.to_string();
    };
    if !is_ident(name.trim()) || line.len() != t.len() {
        return line.to_string();
    }
    for file in [dir.join(format!("{}.rs", name.trim())), dir.join(name.trim()).join("mod.rs")] {
        if file.is_file() {
            return format!("#[path = {:?}] {line}", slashed(&file));
        }
    }
    line.to_string()
}

fn server_root(root: &Path) -> String {
    let api = if crate::api::scan(root).is_ok_and(|e| e.iter().any(|e| !e.methods.is_empty())) {
        "let app = app.merge(yawn_app::api::router());\n    "
    } else {
        ""
    };
    let configure = if server_file(root).is_some() {
        "let app = yawn_app::server::configure(app);\n    "
    } else {
        ""
    };
    format!(
        "// @generated by yawn-rsx for src/main.rsx. Do not edit; changes are overwritten.\nfn main() -> std::process::ExitCode {{\n    let app = yawn::server::App::new(env!(\"CARGO_PKG_NAME\")).ssr::<yawn_app::App>();\n    {api}{configure}app.start()\n}}\n"
    )
}

/// Combined CSS of all `style { }` blocks; served by the dev server as `/pkg/rsx.css`
pub const CSS_FILE: &str = "target/yawn/dist/pkg/rsx.css";

/// A diagnostic together with the file it belongs to
#[derive(Debug, Clone)]
pub struct FileDiagnostic {
    /// Path relative to the project root, with `/` separators
    pub path: String,
    pub source: String,
    pub diagnostic: Diagnostic,
}

impl FileDiagnostic {
    pub fn render(&self) -> String {
        self.diagnostic.render(&self.path, &self.source)
    }
}

#[derive(Debug, Default, Clone)]
pub struct Report {
    /// Source files (relative, `/`) compiled
    pub sources: Vec<String>,
    /// Generated files that changed on disk; unchanged ones are left alone so cargo doesn't
    /// rebuild
    pub written: usize,
}

/// Whether `src/routes/` is turned into routes: on unless `Yawn.toml` has `[router] folders =
/// false`
pub fn folders_enabled(root: &Path) -> bool {
    fs::read_to_string(root.join("Yawn.toml"))
        .ok()
        .and_then(|t| t.parse::<toml::Table>().ok())
        .and_then(|t| t.get("router")?.get("folders")?.as_bool())
        .unwrap_or(true)
}

/// Name of the generated file (without `.rs`) for the `.rsx` file `stem` (below `src/`, no
/// extension): the stem itself, except in `src/routes/` where `[id]` is `param_id` and so on
pub fn generated_stem(root: &Path, stem: &str) -> String {
    if stem.starts_with("routes/")
        && folders_enabled(root)
        && let Ok(r) = crate::routes::analyze(stem, "_")
    {
        return r.module.join("/");
    }
    stem.to_string()
}

/// Whether the project has route files that folder routing will use
pub fn uses_routes(root: &Path) -> bool {
    folders_enabled(root) && find_sources(root).iter().any(|s| s.starts_with("routes/"))
}

pub fn out_dir(root: &Path) -> PathBuf {
    root.join(OUT_DIR)
}

/// All `.rsx` files below `src/`, sorted, as paths relative to `src/` using `/`
pub fn find_sources(root: &Path) -> Vec<String> {
    fn walk(dir: &Path, prefix: &str, out: &mut Vec<String>) {
        let Ok(rd) = fs::read_dir(dir) else { return };
        let mut entries: Vec<_> = rd.flatten().collect();
        entries.sort_by_key(|e| e.file_name());
        for e in entries {
            let name = e.file_name().to_string_lossy().into_owned();
            let rel = if prefix.is_empty() { name.clone() } else { format!("{prefix}/{name}") };
            let path = e.path();
            if path.is_dir() {
                walk(&path, &rel, out);
            } else if name.ends_with(".rsx") {
                out.push(rel);
            }
        }
    }
    let mut out = Vec::new();
    walk(&root.join("src"), "", &mut out);
    out
}

fn problem(path: &str, message: String) -> FileDiagnostic {
    FileDiagnostic {
        path: path.to_string(),
        source: String::new(),
        diagnostic: Diagnostic::new(message, 0..0),
    }
}

fn write_if_changed(path: &Path, content: &str) -> std::io::Result<bool> {
    if fs::read_to_string(path).is_ok_and(|old| old == content) {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, content)?;
    Ok(true)
}

/// Compiles all `.rsx` files of the project at `root`
pub fn compile_project(root: &Path) -> Result<Report, Vec<FileDiagnostic>> {
    compile_project_with(root, split_enabled(root))
}

/// Whether development splits the project into crates: on unless `Yawn.toml` has `[dev] split =
/// false`
pub fn split_enabled(root: &Path) -> bool {
    fs::read_to_string(root.join("Yawn.toml"))
        .ok()
        .and_then(|t| t.parse::<toml::Table>().ok())
        .and_then(|t| t.get("dev")?.get("split")?.as_bool())
        .unwrap_or(true)
}

fn path_dependencies_of(root: &Path) -> Vec<PathBuf> {
    let Ok(text) = fs::read_to_string(root.join("Cargo.toml")) else {
        return vec![];
    };
    let Ok(manifest) = text.parse::<toml::Table>() else {
        return vec![];
    };
    let mut tables: Vec<&toml::Table> = ["dependencies", "build-dependencies"]
        .iter()
        .filter_map(|k| manifest.get(*k)?.as_table())
        .collect();
    if let Some(targets) = manifest.get("target").and_then(|t| t.as_table()) {
        tables.extend(targets.values().filter_map(|t| t.get("dependencies")?.as_table()));
    }
    let mut out: Vec<PathBuf> = Vec::new();
    for deps in tables {
        for dep in deps.values() {
            let Some(path) = dep.as_table().and_then(|t| t.get("path")).and_then(|p| p.as_str())
            else {
                continue;
            };
            let dir = root.join(path);
            if dir.is_dir() {
                let dir = fs::canonicalize(&dir).unwrap_or(dir);
                if !out.contains(&dir) {
                    out.push(dir);
                }
            }
        }
    }
    out
}

/// Library crates of the project: path dependencies in its `Cargo.toml` whose directory is a Yawn
/// project of its own (it has a `Yawn.toml`)
pub fn libraries(root: &Path) -> Vec<PathBuf> {
    path_dependencies_of(root).into_iter().filter(|dir| dir.join("Yawn.toml").is_file()).collect()
}

/// The crates the project is built from besides itself and its component libraries: path
/// dependencies that are plain Rust crates (a shared model, a text renderer), followed through the
/// dependencies of the libraries and of each other
pub fn source_crates(root: &Path) -> Vec<PathBuf> {
    let root = fs::canonicalize(root).unwrap_or_else(|_| root.to_path_buf());
    let mut seen: Vec<PathBuf> = vec![root.clone()];
    let mut queue = vec![root];
    let mut out = Vec::new();
    while let Some(dir) = queue.pop() {
        for dep in path_dependencies_of(&dir) {
            if seen.contains(&dep) {
                continue;
            }
            seen.push(dep.clone());
            queue.push(dep.clone());
            if !dep.join("Yawn.toml").is_file() {
                out.push(dep);
            }
        }
    }
    out
}

/// The packages that are the application's own code, as cargo names them: the component libraries,
/// the plain path crates, and the crates a split project is cut into
pub fn app_packages(root: &Path) -> Vec<String> {
    let framework = |name: &str| {
        name == "yawn"
            || (name.starts_with("yawn-") && !name.starts_with(crate::manifest::MEMBER_PREFIX))
    };
    let mut out: Vec<String> = Vec::new();
    for dir in libraries(root).into_iter().chain(source_crates(root)) {
        if let Some(name) = crate::manifest::package_name(&dir).filter(|n| !framework(n))
            && !out.contains(&name)
        {
            out.push(name);
        }
    }
    // the generated members of a split project (`.yawn/crates/<dir>/Cargo.toml`)
    if let Ok(entries) = fs::read_dir(root.join(".yawn").join("crates")) {
        for entry in entries.flatten() {
            if let Some(name) = crate::manifest::package_name(&entry.path())
                && !out.contains(&name)
            {
                out.push(name);
            }
        }
    }
    out
}

/// [`compile_project`] with the split decided by the caller: `yawn build` passes `false` (one
/// crate, see `split`)
pub fn compile_project_with(root: &Path, split: bool) -> Result<Report, Vec<FileDiagnostic>> {
    // component libraries first: the project's own files use them
    let mut lib_errors = Vec::new();
    let mut lib_report = Report::default();
    for lib in libraries(root) {
        let name = lib.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        match compile_project_with(&lib, false) {
            Ok(r) => {
                lib_report.written += r.written;
                lib_report.sources.extend(r.sources.into_iter().map(|s| format!("{name}/{s}")));
            }
            Err(errs) => lib_errors.extend(errs.into_iter().map(|mut e| {
                e.path = format!("{name}/{}", e.path);
                e
            })),
        }
    }
    match compile_own(root, split) {
        Ok(mut report) => {
            report.written += lib_report.written;
            report.sources.extend(lib_report.sources);
            if lib_errors.is_empty() { Ok(report) } else { Err(lib_errors) }
        }
        Err(mut errs) => {
            lib_errors.append(&mut errs);
            Err(lib_errors)
        }
    }
}

fn compile_own(root: &Path, split: bool) -> Result<Report, Vec<FileDiagnostic>> {
    let out = out_dir(root);
    let sources = find_sources(root);
    let mut errors = Vec::new();
    let mut report = Report::default();
    // module path -> generated file
    let mut modules: BTreeMap<Vec<String>, PathBuf> = BTreeMap::new();
    let mut keep: Vec<PathBuf> = Vec::new();
    let mut css = String::new();

    // which props of which components may be left out, read from every file before any is compiled
    let mut known = crate::codegen::Registry::new();
    let mut seen: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    let mut twice: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    // components of the project's libraries are called from its files, so their defaults count too
    let mut header_files: Vec<PathBuf> =
        sources.iter().map(|rel| root.join(format!("src/{rel}"))).collect();
    for lib in libraries(root) {
        header_files
            .extend(find_sources(&lib).into_iter().map(|rel| lib.join(format!("src/{rel}"))));
    }
    for file in &header_files {
        if let Ok(text) = fs::read_to_string(file) {
            for h in crate::parser::headers(&text) {
                if !seen.insert(h.name.clone()) {
                    twice.insert(h.name.clone());
                }
                if !h.defaults.is_empty() {
                    known.insert(h.name, h.defaults);
                }
            }
        }
    }
    // two components of one name can't be told apart at a call site: leaving a prop out is an error there
    known.retain(|name, _| !twice.contains(name));
    let mut has_entry = false;
    let mut client_text: Option<String> = None;
    let mut router = false;
    let folders = folders_enabled(root);
    let mut route_files: Vec<crate::routes::Route> = Vec::new();
    for rel in &sources {
        let display = format!("src/{rel}");
        let stem = rel.trim_end_matches(".rsx");
        if rel == ENTRY {
            has_entry = true;
            let source = match fs::read_to_string(root.join(&display)) {
                Ok(s) => s,
                Err(e) => {
                    errors.push(problem(&display, format!("cannot read file: {e}")));
                    continue;
                }
            };
            if !crate::parser::headers(&source).iter().any(|h| h.name == "App") {
                errors.push(FileDiagnostic {
                    path: display,
                    source,
                    diagnostic: Diagnostic::new("`src/main.rsx` must declare `component App()`: it is the component the browser mounts", 0..0),
                });
                continue;
            }
            match crate::compile_with(&source, &display, &known) {
                Ok(c) => {
                    css.push_str(&c.css);
                    let map_path = out.join("main.map");
                    let map_text = SourceMap { source: display.clone(), ..c.map }.to_text();
                    // the client root is written below, once the module list is known (the split may move modules out of it)
                    client_text = Some(client_root(root, &c.rust));
                    let wrote = write_if_changed(&root.join(SERVER_ROOT), &server_root(root))
                        .and_then(|a| write_if_changed(&map_path, &map_text).map(|b| a || b));
                    match wrote {
                        Ok(changed) => report.written += changed as usize,
                        Err(e) => errors
                            .push(problem(&display, format!("cannot write generated code: {e}"))),
                    }
                    if let Err(problems) = crate::api::scan(root) {
                        for (path, message) in problems {
                            errors.push(problem(&path, message));
                        }
                    }
                    router = folders && sources.iter().any(|s| s.starts_with("routes/"));
                    for old in
                        ["src/lib.rs", "src/main.rs", "src/.yawn-client.rs", "src/.yawn-server.rs"]
                    {
                        let path = root.join(old);
                        if fs::read_to_string(&path).is_ok_and(|t| t.starts_with("// @generated")) {
                            // left by an earlier version, which wrote the crate roots into src/
                            let _ = fs::remove_file(&path);
                        } else if (old.ends_with("lib.rs") || old.ends_with("main.rs"))
                            && path.is_file()
                        {
                            errors.push(problem(old, format!("`{old}` would be ignored: with `src/main.rsx` the crate roots are generated; delete it or `src/main.rsx`")));
                        }
                    }
                    keep.push(map_path);
                    report.sources.push(display);
                }
                Err(diagnostic) => {
                    errors.push(FileDiagnostic { path: display, source, diagnostic })
                }
            }
            continue;
        }
        let source = match fs::read_to_string(root.join(&display)) {
            Ok(s) => s,
            Err(e) => {
                errors.push(problem(&display, format!("cannot read file: {e}")));
                continue;
            }
        };
        let module: Vec<String> = if folders && rel.starts_with("routes/") {
            let component = crate::routes::component_name(stem);
            if !crate::parser::headers(&source).iter().any(|h| h.name == component) {
                errors.push(FileDiagnostic {
                    path: display,
                    source,
                    diagnostic: Diagnostic::new(format!("a route file must declare the component `{component}`, named after the file: `component {component}() {{ ... }}`"), 0..0),
                });
                continue;
            }
            match crate::routes::analyze(stem, &component) {
                Ok(mut r) => {
                    r.preload = crate::routes::declares_preload(&source);
                    let module = r.module.clone();
                    route_files.push(r);
                    module
                }
                Err(e) => {
                    errors.push(problem(&display, e));
                    continue;
                }
            }
        } else {
            let module: Vec<String> = stem.split('/').map(str::to_string).collect();
            if let Some(bad) = module.iter().find(|m| !is_ident(m)) {
                errors.push(problem(&display, format!("`{bad}` is not a valid Rust module name; rename the file (letters, digits, `_`)")));
                continue;
            }
            module
        };
        if modules.contains_key(&module) {
            errors.push(problem(
                &display,
                format!("another file is already module `{}`", module.join("::")),
            ));
            continue;
        }
        // generated files are named after the module (`[id].rsx` is `param_id.rs`)
        let stem = &module.join("/");
        let rust_name = format!("{stem}.rs");
        if root.join("src").join(&rust_name).exists()
            || root.join("src").join(stem).join("mod.rs").exists()
        {
            errors.push(problem(
                &display,
                format!(
                    "`src/{rust_name}` already exists: both would be module `{}`",
                    module.join("::")
                ),
            ));
            continue;
        }
        match crate::compile_with(&source, &display, &known) {
            Ok(c) => {
                css.push_str(&c.css);
                let gen_path = out.join(&rust_name);
                let map_path = out.join(format!("{stem}.map"));
                let map_text = SourceMap { source: display.clone(), ..c.map }.to_text();
                let wrote = write_if_changed(&gen_path, &c.rust)
                    .and_then(|a| write_if_changed(&map_path, &map_text).map(|b| a || b));
                match wrote {
                    Ok(changed) => report.written += changed as usize,
                    Err(e) => {
                        errors.push(problem(&display, format!("cannot write generated code: {e}")))
                    }
                }
                keep.push(gen_path.clone());
                keep.push(map_path);
                modules.insert(module, gen_path);
                report.sources.push(display);
            }
            Err(diagnostic) => errors.push(FileDiagnostic { path: display, source, diagnostic }),
        }
    }
    if !errors.is_empty() {
        // a project with errors still gets its crate root and manifest once; the split waits for a build that succeeds
        if let Some(client) = &client_text
            && !root.join(CLIENT_ROOT).is_file()
        {
            let _ = write_if_changed(&root.join(CLIENT_ROOT), client);
            let _ = crate::manifest::write(root, router, &[]);
        }
        return Err(errors);
    }

    if !has_entry {
        // The entry point went away: so do the roots generated from it.
        for f in [CLIENT_ROOT, SERVER_ROOT, crate::manifest::MANIFEST, crate::manifest::LOCK] {
            if fs::read_to_string(root.join(f)).is_ok_and(|t| {
                t.starts_with("// @generated")
                    || t.starts_with("# @generated")
                    || f.ends_with(".lock")
            }) {
                let _ = fs::remove_file(root.join(f));
            }
        }
    }
    let css_path = root.join(CSS_FILE);
    if css.is_empty() {
        let _ = fs::remove_file(&css_path);
    } else if let Err(e) = write_if_changed(&css_path, &css) {
        return Err(vec![problem(CSS_FILE, format!("cannot write: {e}"))]);
    }

    let (modules_rs, mut folder_files) = modules_file(root, &out, &modules);
    if !route_files.is_empty() {
        // the route table lives in the `routes` module, so using it's an explicit import
        let mod_rs = out.join("routes").join("mod.rs");
        if let Some((_, text)) = folder_files.iter_mut().find(|(p, _)| *p == mod_rs) {
            text.push_str(&crate::routes::table(&route_files));
        }
    }
    if let Ok(endpoints) = crate::api::scan(root)
        && !endpoints.is_empty()
    {
        folder_files
            .extend(crate::api::module_files(&out.join(crate::api::MODULE_DIR), &endpoints));
    }
    for (path, text) in folder_files {
        match write_if_changed(&path, &text) {
            Ok(changed) => report.written += changed as usize,
            Err(e) => {
                return Err(vec![problem(
                    ".yawn/rsx",
                    format!("cannot write {}: {e}", path.display()),
                )]);
            }
        }
        keep.push(path);
    }
    // one crate, or several (see `split`)
    let split = client_text
        .as_ref()
        .filter(|_| split)
        .and_then(|c| crate::split::apply(root, c, &modules_rs));
    let (modules_rs, members) = match &split {
        Some(sp) => (sp.modules.clone(), sp.members.clone()),
        None => (modules_rs, Vec::new()),
    };
    if let Some(client) = split.as_ref().map(|sp| &sp.client).or(client_text.as_ref()) {
        match write_if_changed(&root.join(CLIENT_ROOT), client) {
            Ok(changed) => report.written += changed as usize,
            Err(e) => {
                return Err(vec![problem(
                    CLIENT_ROOT,
                    format!("cannot write generated code: {e}"),
                )]);
            }
        }
        match crate::manifest::write(root, router, &members) {
            Ok(changed) => report.written += changed as usize,
            Err(e) => return Err(vec![problem("Cargo.toml", e)]),
        }
    }
    let crates_dir = root.join(crate::split::CRATES_DIR);
    let mut keep_crates: Vec<PathBuf> = Vec::new();
    for (path, text) in split.iter().flat_map(|sp| sp.files.iter()) {
        match write_if_changed(path, text) {
            Ok(changed) => report.written += changed as usize,
            Err(e) => {
                return Err(vec![problem(
                    ".yawn/crates",
                    format!("cannot write {}: {e}", path.display()),
                )]);
            }
        }
        keep_crates.push(path.clone());
        keep_crates.push(path.with_file_name("Cargo.toml"));
    }
    remove_stale(&crates_dir, &keep_crates);
    keep.push(out.join("modules.rs"));
    match write_if_changed(&out.join("modules.rs"), &modules_rs) {
        Ok(changed) => report.written += changed as usize,
        Err(e) => return Err(vec![problem(".yawn/rsx/modules.rs", format!("cannot write: {e}"))]),
    }
    remove_stale(&out, &keep);
    Ok(report)
}

fn is_ident(s: &str) -> bool {
    !s.is_empty()
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !s.starts_with(|c: char| c.is_ascii_digit())
        && !matches!(
            s,
            "crate"
                | "self"
                | "super"
                | "mod"
                | "fn"
                | "use"
                | "type"
                | "struct"
                | "enum"
                | "impl"
                | "trait"
                | "pub"
                | "mut"
                | "ref"
                | "move"
                | "static"
                | "const"
        )
}

#[derive(Default)]
struct Tree {
    files: BTreeMap<String, PathBuf>,
    dirs: BTreeMap<String, Tree>,
}

fn modules_file(
    root: &Path,
    out: &Path,
    modules: &BTreeMap<Vec<String>, PathBuf>,
) -> (String, Vec<(PathBuf, String)>) {
    let mut tree = Tree::default();
    for (path, file) in modules {
        let mut node = &mut tree;
        for dir in &path[..path.len() - 1] {
            node = node.dirs.entry(dir.clone()).or_default();
        }
        node.files.insert(path.last().unwrap().clone(), file.clone());
    }
    fn declarations(
        root: &Path,
        t: &Tree,
        rel: &Path,
        dir: &Path,
        text: &mut String,
        files: &mut Vec<(PathBuf, String)>,
    ) {
        for (name, file) in &t.files {
            text.push_str(&format!("#[path = {:?}]\npub mod {name};\n", slashed(file)));
        }
        for (name, sub) in &t.dirs {
            let sub_dir = dir.join(name);
            let mod_rs = sub_dir.join("mod.rs");
            text.push_str(&format!("#[path = {:?}]\npub mod {name};\n", slashed(&mod_rs)));
            let mut sub_text =
                String::from("// @generated by yawn-rsx: the modules of this folder.\n");
            // a folder that has plain Rust of its own (`src/<folder>/mod.rs`) keeps it: its `mod x;` lines point at the files next to it
            let src_dir = root.join("src").join(rel).join(name);
            if let Ok(plain) = fs::read_to_string(src_dir.join("mod.rs")) {
                for line in plain.lines() {
                    sub_text.push_str(&path_mod_in(&src_dir, line));
                    sub_text.push('\n');
                }
            }
            declarations(root, sub, &rel.join(name), &sub_dir, &mut sub_text, files);
            files.push((mod_rs, sub_text));
        }
    }
    let mut text = String::from("// @generated by yawn-rsx: the `.rsx` modules of this crate.\n");
    let mut files = Vec::new();
    declarations(root, &tree, Path::new(""), out, &mut text, &mut files);
    (text, files)
}

fn remove_stale(dir: &Path, keep: &[PathBuf]) {
    let Ok(rd) = fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            remove_stale(&p, keep);
            let _ = fs::remove_dir(&p); // only succeeds when empty
        } else if !keep.contains(&p) {
            let _ = fs::remove_file(&p);
        }
    }
}

